package Curso_Java6;

public class TiposDeDatosNoPrimitivos {

    
    public static void main(String[] args) {
        //Variables no primitivas 
        System.out.println("***************Variables no primitivas***************\n");
        
        //Variable com Integer
        Integer numero = null;  //Esta variable es de tipo entero no primitiva y acepta el valor de null
        System.out.println("Variable entera con Integer: " + numero);
        
        //Variable com String "Cadenas"
        String caracteres = "Hola que tal"; //Esta variable es de tipo cadena 
        System.out.println("Variable de cadenas de caracteres: " + caracteres );
  
    }
    
}
