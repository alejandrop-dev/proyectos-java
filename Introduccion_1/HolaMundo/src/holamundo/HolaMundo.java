package holamundo;

public class HolaMundo {
    
    public static void main(String[] args) {
        //Datos primitivos 
        
        // Entre los nuemros enteros se encuentra el: byte , short , int , long 
        System.out.println("***************Variables de tipo entero***************\n");
        
        // Numero entero con byte
        byte Entero_byte =12;   
        System.out.println("Numero entero con byte: " + Entero_byte);
        
        //Numero entero con short
        short Entero_short =156;   
        System.out.println("Numero entero con short: " + Entero_short);
        
        //Numero entero con int
        int Entero_int =12456;   
        System.out.println("Numero entero con int: " + Entero_int);
        
        //Numero entero con long
        long Entero_long =32458;   
        System.out.println("Numero entero con long: " + Entero_long);
        
        
        
        // Entre los numeros con decimales se encuentra el: float y double
        System.out.println("\n***************Variables de tipo reales***************\n");
        
        //Numeros reales con float
        float Decimal_float = 3.45f;
        System.out.println("Numero decimal con float: " + Decimal_float);
        
        double Decimal_double = 5421.5466121;
        System.out.println("Numero decimal con double: " + Decimal_double);
        
        
        
        //Entre los caracteres tenemos
        System.out.println("\n***************Variables de tipo caracter***************\n");
        
        //Caracter con char
        char caracter_char = 'a';
        System.out.println("Caracter con char: " + caracter_char);
        
        //Caracter con booleano 
        boolean decision = true;    //Solo puede ser true o false  
        System.out.println("El valor booleano es: "+ decision);
        
        
        
    }
    
}
